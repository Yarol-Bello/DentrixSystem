package com.dentrix.model;

public class ConfiguracionClinica {
    private int id;
    private String ruc;
    private String razonSocial;
    private String nombreComercial;
    private String direccionFiscal;
    private String serieBoleta;
    private String celularYape;
    private String titularYape;
    private String directorMedico;
    private String cop;
    private String rne;
    private String licenciaMunicipal;

    // Getters y Setters
    public int getId() { return id; }
    public void setId(int id) { this.id = id; }
    public String getRuc() { return ruc; }
    public void setRuc(String ruc) { this.ruc = ruc; }
    public String getRazonSocial() { return razonSocial; }
    public void setRazonSocial(String razonSocial) { this.razonSocial = razonSocial; }
    public String getNombreComercial() { return nombreComercial; }
    public void setNombreComercial(String nombreComercial) { this.nombreComercial = nombreComercial; }
    public String getDireccionFiscal() { return direccionFiscal; }
    public void setDireccionFiscal(String direccionFiscal) { this.direccionFiscal = direccionFiscal; }
    public String getSerieBoleta() { return serieBoleta; }
    public void setSerieBoleta(String serieBoleta) { this.serieBoleta = serieBoleta; }
    public String getCelularYape() { return celularYape; }
    public void setCelularYape(String celularYape) { this.celularYape = celularYape; }
    public String getTitularYape() { return titularYape; }
    public void setTitularYape(String titularYape) { this.titularYape = titularYape; }
    public String getDirectorMedico() { return directorMedico; }
    public void setDirectorMedico(String directorMedico) { this.directorMedico = directorMedico; }
    public String getCop() { return cop; }
    public void setCop(String cop) { this.cop = cop; }
    public String getRne() { return rne; }
    public void setRne(String rne) { this.rne = rne; }
    public String getLicenciaMunicipal() { return licenciaMunicipal; }
    public void setLicenciaMunicipal(String licenciaMunicipal) { this.licenciaMunicipal = licenciaMunicipal; }
}